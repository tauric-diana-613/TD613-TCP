export function affineOf(x) {
  if (!validG(x)) return null;
  const linear = parity(x.t)===0 ? I3 : A;
  return freeze({ A:linear, v:freeze([x.E,x.O,x.t/2]) });
}

export function composeAffine(left,right) {
  return freeze({A:freeze(matMul(left.A,right.A).map((r)=>freeze(r))), v:freeze(vecAdd(matVec(left.A,right.v),left.v))});
}

export function applyAffine(aff,p) {
  return freeze(vecAdd(matVec(aff.A,p),aff.v));
}

export function affineRepresentationCertificate() {
  const parent=torsionFreeCertificate();
  const Taff=affineOf(gT());
  const eaff=affineOf(gE()), oaff=affineOf(gO()), saff=affineOf(gS());
  const relations=freeze({
    A_squared_I:same(matMul(A,A),I3),
    determinant:det3(A),
    T_squared_s:same(composeAffine(Taff,Taff),saff),
    T_formula:same(applyAffine(Taff,[2,3,5]),[3,2,5.5]),
  });
  const states=[];
  for (const t of [-2,-1,0,1,2]) for (const E of [-1,0,1]) for (const O of [-1,0,1]) states.push(freeze({t,E,O}));
  const pairRows=[];
  for (const x of states) for (const y of states) {
    const xy=integerFractionGroupMultiply(x,y);
    pairRows.push(freeze({x,y,passed:same(composeAffine(affineOf(x),affineOf(y)),affineOf(xy))}));
  }
  const identityKernelRows=states.map((x)=>{
    const aff=affineOf(x);
    const isId=same(aff.A,I3)&&same(aff.v,[0,0,0]);
    const groupId=x.t===0&&x.E===0&&x.O===0;
    return freeze({x,isId,groupId,passed:isId===groupId});
  });
  const passed=parent.passed
    && Object.values(relations).every((v)=>v===true||v===-1)
    && relations.determinant===-1
    && pairRows.every((r)=>r.passed)
    && identityKernelRows.every((r)=>r.passed);
  return freeze({
    status:passed ? 'AFFINE_REPRESENTATION_CERTIFICATE_PASSED' : 'AFFINE_REPRESENTATION_CERTIFICATE_FAILED',
    passed,
    glide_formula:'rho(T)(x,y,z)=(y,x,z+1/2)',
    general_formula:'rho(t,E,O): A^(t mod2) with translation (E,O,t/2)',
    linear_generator:A,
    determinant:det3(A),
    relations,
    homomorphism_sample_pairs:pairRows.length,
    homomorphism_rows_pass:pairRows.every((r)=>r.passed),
    faithfulness_rows_pass:identityKernelRows.every((r)=>r.passed),
    faithful:passed,
    euclidean_isometries:passed,
  });
}

