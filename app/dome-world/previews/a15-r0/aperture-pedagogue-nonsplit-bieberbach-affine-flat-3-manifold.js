const freeze = (value) => {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.values(value).forEach(freeze);
    Object.freeze(value);
  }
  return value;
};

const parity = (n) => ((n % 2) + 2) % 2;
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const validG = (x) => x && typeof x === 'object' && [x.t, x.E, x.O].every(Number.isInteger);

const I3 = freeze([[1,0,0],[0,1,0],[0,0,1]].map((r) => freeze(r)));
const A = freeze([[0,1,0],[1,0,0],[0,0,1]].map((r) => freeze(r)));

function matMul(X, Y) {
  return X.map((row) => Y[0].map((_, j) => row.reduce((s, v, k) => s + v * Y[k][j], 0)));
}
function matVec(X, v) {
  return X.map((row) => row.reduce((s, a, i) => s + a * v[i], 0));
}
function vecAdd(a, b) { return a.map((v, i) => v + b[i]); }
function det3(M) {
  const [a,b,c]=M[0], [d,e,f]=M[1], [g,h,i]=M[2];
  return a*(e*i-f*h)-b*(d*i-f*g)+c*(d*h-e*g);
}

export function gUnit() { return freeze({ t:0, E:0, O:0 }); }
export function gT() { return freeze({ t:1, E:0, O:0 }); }
export function gE() { return freeze({ t:0, E:1, O:0 }); }
export function gO() { return freeze({ t:0, E:0, O:1 }); }
export function gS() { return freeze({ t:2, E:0, O:0 }); }

export function kernelCoordinates(x) {
  if (!validG(x) || parity(x.t) !== 0) return null;
  return freeze({ a:x.E, b:x.O, c:x.t/2 });
}

export function kernelElement({ a, b, c }) {
  if (![a,b,c].every(Number.isInteger)) return null;
  return freeze({ t:2*c, E:a, O:b });
}

export function tauK(k) {
  return freeze({ a:k.b, b:k.a, c:k.c });
}

export function normK(k) {
  const tk = tauK(k);
  return freeze({ a:k.a+tk.a, b:k.b+tk.b, c:k.c+tk.c });
}

export function parityExtensionCertificate() {
  const T=gT(), e=gE(), o=gO(), s=gS(), one=gUnit();
  const T2 = integerFractionGroupMultiply(T,T);
  const Tinv = integerFractionGroupInverse(T);
  const conj = (x) => integerFractionGroupMultiply(integerFractionGroupMultiply(T,x),Tinv);
  const rows = [];
  for (const t of [-2,-1,0,1,2]) for (const E of [-1,0,1]) for (const O of [-1,0,1]) {
    const x=freeze({t,E,O});
    const k=kernelCoordinates(x);
    rows.push(freeze({x,in_kernel:parity(t)===0,k,roundtrip:k ? same(kernelElement(k),x) : true}));
  }
  const passed = same(T2,s)
    && same(conj(e),o) && same(conj(o),e) && same(conj(s),s)
    && rows.every((r)=>r.roundtrip)
    && same(integerFractionGroupMultiply(T,Tinv),one);
  return freeze({
    status: passed ? 'PARITY_EXTENSION_CERTIFICATE_PASSED' : 'PARITY_EXTENSION_CERTIFICATE_FAILED',
    passed,
    parent_receipt:NONSPLIT_BIEBERBACH_AFFINE_FLAT_3_MANIFOLD_PARENT_RECEIPT,
    quotient:'C2 by t mod 2',
    kernel:passed ? 'K={t even} ≅ Z^3' : 'UNEARNED',
    basis:passed ? 'e=(0,1,0), o=(0,0,1), s=(2,0,0)' : 'UNEARNED',
    T_squared:T2,
    conjugation:freeze({e:conj(e),o:conj(o),s:conj(s)}),
    sample_rows:freeze(rows),
  });
}

