export const SECOND_AMPHICOSM_TIETZE_EXACTIFICATION_SCHEMA = 'td613.a15-r0.second-amphicosm-tietze-exactification/v0.1';

const freeze = (value) => {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.values(value).forEach(freeze);
    Object.freeze(value);
  }
  return value;
};

export function reverseTietzeCertificate() {
  const forward = conwayRossettiGeneratorCertificate();
  const proofSteps = freeze([
    freeze({
      id: 'E_COMMUTES_Z',
      identity: 'e^-1 Z e = W X^-1 Z X W^-1 = W Z^-1 W^-1 = Z',
      role: 'e commutes with Z',
    }),
    freeze({
      id: 'COMMUTATOR_REWRITE',
      identity: '[X,W]=Z implies W^-1 X W = X Z',
      role: 'rewrite the negative-amphicosm commutator relation',
    }),
    freeze({
      id: 'OPPOSITE_CONJUGATION',
      identity: 'conjugating the previous identity and using W Z W^-1=Z^-1 gives W X W^-1 = X Z',
      role: 'same XZ correction under the inverse conjugation',
    }),
    freeze({
      id: 'O_EQUALS_E_Z_INVERSE',
      identity: 'o=W e W^-1=W(XW^-1)W^-1=e Z^-1',
      role: 'express o in the commuting translation subgroup generated by e and Z',
    }),
    freeze({
      id: 'E_O_COMMUTE',
      identity: '[e,o]=1 because o=eZ^-1 and [e,Z]=1',
      role: 'recover the parent Z^2 fiber relation',
    }),
    freeze({
      id: 'T_SWAPS_E_TO_O',
      identity: 'T e T^-1 = W e W^-1 = o',
      role: 'first swap relation',
    }),
    freeze({
      id: 'T_SWAPS_O_TO_E',
      identity: 'T o T^-1 = W(eZ^-1)W^-1 = o Z = e',
      role: 'second swap relation',
    }),
  ]);

  const substitutions = freeze({
    forward_parent_to_amphicosm: freeze({ W: 'T', X: 'eT', Z: 'e o^-1' }),
    reverse_amphicosm_to_parent: freeze({ T: 'W', e: 'XW^-1', o: 'W e W^-1' }),
  });

  const requiredIds = freeze([
    'E_COMMUTES_Z',
    'COMMUTATOR_REWRITE',
    'OPPOSITE_CONJUGATION',
    'O_EQUALS_E_Z_INVERSE',
    'E_O_COMMUTE',
    'T_SWAPS_E_TO_O',
    'T_SWAPS_O_TO_E',
  ]);
  const ids = proofSteps.map((step) => step.id);
  const complete = requiredIds.every((id) => ids.includes(id)) && ids.length === requiredIds.length;
  const passed = forward.passed
    && complete
    && Object.values(forward.generation).every(Boolean);

  return freeze({
    status: passed ? 'REVERSE_TIETZE_EXACTIFICATION_CERTIFICATE_PASSED' : 'REVERSE_TIETZE_EXACTIFICATION_CERTIFICATE_FAILED',
    passed,
    parent_receipt: SECOND_AMPHICOSM_IDENTIFICATION_RIGIDITY_PARENT_RECEIPT,
    source_negative_amphicosm_presentation: '<W,X,Z | W^-1ZW=Z^-1, X^-1ZX=Z^-1, [X,W]=Z>',
    inherited_parent_presentation: '<T,e,o | [e,o]=1, T e T^-1=o, T o T^-1=e>',
    substitutions,
    proof_steps: proofSteps,
    proof_step_ids_complete: complete,
    classification_if_passed: 'THE_PARENT_AND_NEGATIVE_AMPHICOSM_PRESENTATIONS_ARE_TIETZE_EQUIVALENT.',
    scar: 'RELATION_MATCH_PLUS_GENERATION != PRESENTATION_ISOMORPHISM_WITHOUT_REVERSE_TIETZE_CERTIFICATE',
  });
}

export function exactSecondAmphicosmIdentificationCertificate() {
  const tietze = reverseTietzeCertificate();
  const h1 = amphicosmH1FingerprintCertificate();
  const first = firstAmphicosmExclusionCertificate();
  const passed = tietze.passed && h1.passed && first.passed;
  return freeze({
    status: passed ? 'EXACT_SECOND_NEGATIVE_AMPHICOSM_IDENTIFICATION_PASSED' : 'EXACT_SECOND_NEGATIVE_AMPHICOSM_IDENTIFICATION_FAILED',
    passed,
    tietze_equivalence: tietze,
    H1_fingerprint: h1,
    positive_first_exclusion: first,
    classical_name: passed ? 'second amphicosm' : 'UNEARNED',
    conway_rossetti_symbol: passed ? '-a1' : 'UNEARNED',
    wolf_label: passed ? 'B2' : 'UNEARNED',
    exact_group_isomorphism_if_passed: passed
      ? 'G ≅ pi_1(second amphicosm -a1)'
      : 'UNEARNED',
  });
}

export function exactBieberbachRigidityCertificate() {
  const identification = exactSecondAmphicosmIdentificationCertificate();
  const product = productTypeExclusionCertificate();
  const standardTheorem = freeze({
    name: 'Bieberbach affine rigidity theorem for Euclidean crystallographic groups',
    statement: 'An abstract isomorphism of Euclidean crystallographic groups is induced by affine conjugacy.',
    application_ceiling: 'affine equivalence type, not a unique isometric metric',
  });
  const passed = identification.passed && product.passed;
  return freeze({
    status: passed ? 'EXACT_BIEBERBACH_RIGIDITY_APPLICATION_PASSED' : 'EXACT_BIEBERBACH_RIGIDITY_APPLICATION_FAILED',
    passed,
    identification,
    product_type_exclusion: product,
    standard_theorem: standardTheorem,
    flat_affine_type: passed ? 'second/negative amphicosm -a1' : 'UNEARNED',
    unique_metric_claim: false,
    physical_spacetime_authority: false,
  });
}

