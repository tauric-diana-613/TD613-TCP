assert.equal(prepared.provider_wire.body,read('PROVIDER_REQUEST.body.json').toString('utf8'));
assert.equal(String(prepared.provider_wire.reserved_cost_nanos),'491184000');
mkdirSync(out,{mode:0o700});
const write=(name,x)=>writeFileSync(join(out,name),typeof x==='string'?x:JSON.stringify(x,null,2)+'\n',{flag:'wx',mode:0o600});
write('policy.json',policy);write('request.json',prepared.request);write('provider-request.body.json',prepared.provider_wire.body);
write('ACTIVATION.json',a);
execFileSync(process.execPath,[join(repo,'research/portable-loom-server-transport-20261009/prepare-enrollment.mjs'),join(out,'policy.json'),configuration.access_sha256,join(out,'enrollment.json')],{cwd:repo,stdio:'pipe'});
write('PREPARATION_RECEIPT.json',{status:'PREPARED_NOT_APPLIED',source_commit:head,run_id:protocol.run_id,policy_canonical_sha256:contract.sha256(contract.canonicalJson(policy)),policy_file_bytes_sha256:sha(readFileSync(join(out,'policy.json'))),prompt_sha256:protocol.prompt.sha256,provider_request_sha256:prepared.provider_wire.request_sha256,expires_at:policy.expires_at,reserved_cost_nanos:prepared.provider_wire.reserved_cost_nanos,provider_requests:0,reservations:0,enrollments:0,deployments:0});
console.log(JSON.stringify({status:'PREPARED_NOT_APPLIED',run_id:protocol.run_id,source_commit:head,provider_requests:0,reservations:0,enrollments:0,deployments:0}));
