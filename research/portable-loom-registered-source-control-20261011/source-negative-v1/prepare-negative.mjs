assert(!existsSync(out),'Output must be new; never reuse a run/attempt directory.');
const estate=join(repo,'research/portable-loom-registered-source-control-20261011/source-negative-v1');
const read=name=>readFileSync(join(estate,name));
const sha=b=>createHash('sha256').update(b).digest('hex');
const protocol=JSON.parse(read('PROTOCOL.json'));
const a=JSON.parse(readFileSync(activationFile));
const at=Date.now(),recorded=Date.parse(a.recorded_at);
assert.equal(a.status,'ACTIVATED_BY_DIRECT_OPERATOR');
assert.equal(a.operator,'Tawanna C. Miller');
assert.equal(a.authority_class,'INTERACTIVE_OPERATOR_DIRECT');
assert(typeof a.instruction==='string'&&a.instruction.trim());
assert(Number.isFinite(recorded)&&recorded<=at&&at-recorded<=6*3600000);
assert.equal(a.protocol_sha256,sha(read('PROTOCOL.json')));
assert.equal(a.provider_requests,1);assert.equal(a.reservation_ceiling_usd,0.5);
assert.equal(a.automatic_retries,0);assert.equal(a.manual_retries,0);
assert.equal(a.fresh_enrollments,1);assert.equal(a.detached_delegation,false);
assert.equal(protocol.run_id,'portable-loom-source-registration-negative-20261011-n01');
assert.equal(protocol.prompt.sha256,sha(read('PROMPT.txt')));
assert.equal(protocol.prompt.provider_request_sha256,sha(read('PROVIDER_REQUEST.body.json')));
assert.equal(protocol.scoring_contract_sha256,sha(read('SCORING_CONTRACT.json')));
const git=(...args)=>execFileSync('git',['-C',repo,...args],{encoding:'utf8'}).trim();
const head=git('rev-parse','HEAD');assert(/^[a-f0-9]{40}$/.test(head));
assert.equal(git('status','--porcelain'),'');
const configuration=JSON.parse(readFileSync(join(repo,'server/loom-assay-run-config.json')));
assert(configuration.run_ids.includes(protocol.run_id),'New identity has not been explicitly activated in source.');
const policy=JSON.parse(read('POLICY.template.json'));
policy.protocol_commit=head;policy.binding.protocol_commit=head;
policy.expires_at=new Date(at+6*3600000).toISOString();
assert(Date.parse(policy.expires_at)<Date.parse('2027-01-01T00:00:00Z'),'Frozen price window has ended.');
policy.binding.authorization.record=resolve(activationFile);
const contract=await import(pathToFileURL(join(repo,'server/loom-assay-contract.js')));
contract.validateAssayPolicy(policy,at);
const client=await import(pathToFileURL(join(repo,'research/portable-loom-server-transport-20261009/server-client.mjs')));
const loaded=client.loadServerManifest(repo,protocol.run_id);
assert.equal(loaded.manifest.artifact_sha256,protocol.prompt.sha256);
assert.equal(loaded.artifact,read('PROMPT.txt').toString('utf8'));
