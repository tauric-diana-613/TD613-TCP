import fs from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import {createHmac,randomUUID} from 'node:crypto';
import {canonical,digest,equalHex,mac} from '../../experiment-b-resumable/journal.mjs';
import {SAFE_HARBOR_NAMESPACE,EXPERIMENT_B_CUSTODY_LANE,createSafeHarborDispatchBridge} from '../safe-harbor-dispatch-bridge.mjs';

const sha=v=>typeof v==='string'&&/^[a-f0-9]{64}$/.test(v);
const held=code=>{throw Object.assign(Error(code),{code});};
const scope='EXPERIMENT_B_NATIVE_DISPATCH';
const seal=(key,payload)=>{
  const text=canonical(payload),header=Buffer.from(JSON.stringify({alg:'HS256',kid:payload.issuer,typ:'TD613-SCOPED-AUTHORIZATION+JWS'})).toString('base64url');
  return {lane:EXPERIMENT_B_CUSTODY_LANE,payload:text,detachedJws:header+'..'+createHmac('sha256',key).update(header+'.'+Buffer.from(text).toString('base64url')).digest('base64url')};
};
/** Secrets enter only from the separately permissioned custodian host, never IPC.
 * The caller establishes OS identity/ACLs. This class supplies no such attestation.
 * db + anchorLog must already exist after the human-only initialization step.
 */
export class CustodyStore{
  constructor({database,anchorLog,key,checkpointKey,issuer,audience,now=Date.now,externalAudit=null}){
    if(!Buffer.isBuffer(key)||key.length<32||!Buffer.isBuffer(checkpointKey)||checkpointKey.length<32||key.equals(checkpointKey)||!issuer||typeof audience!=='string'||!audience)held('CUSTODIAN_ROOT_REQUIRED');
    if(!fs.existsSync(database)||!fs.existsSync(anchorLog))held('CUSTODIAN_DURABLE_STATE_REQUIRED');
    this.key=Buffer.from(key);this.checkpointKey=Buffer.from(checkpointKey);this.issuer=issuer;this.audience=audience;this.now=now;this.anchorLog=anchorLog;this.externalAudit=externalAudit;
    this.db=new DatabaseSync(database);this.db.exec('PRAGMA busy_timeout=5000; PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL;');
    try{this.db.exec('BEGIN IMMEDIATE');const head=this.verifyAudit();
      if(externalAudit){
        const floor=externalAudit.minimum();
        if(head.seq===0&&floor||head.seq>0&&(!floor||floor.issuer!==issuer||floor.seq!==head.seq||floor.hash!==head.hash||
          !equalHex(floor.tag,mac(this.key,{seq:floor.seq,hash:floor.hash}))))held('INDEPENDENT_SYSTEM_ANCHOR_MISMATCH_HOLD');
      }
      this.db.exec('COMMIT');
    }catch(e){try{this.db.exec('ROLLBACK');}catch{}this.db.close();throw e;}
  }
  static initializeEmpty({database,anchorLog}){
    // Production invocation is restricted to the human-only activation utility.
    // No key is generated by this storage initializer.
    const fd=fs.openSync(database,'wx',0o600);fs.closeSync(fd);
    const db=new DatabaseSync(database);
    try{db.exec(`PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL;
      CREATE TABLE mandates(id TEXT PRIMARY KEY,body TEXT NOT NULL,revoked INTEGER NOT NULL DEFAULT 0);
      CREATE TABLE permits(issuer TEXT NOT NULL,id TEXT NOT NULL,mandate TEXT NOT NULL,attempt TEXT UNIQUE NOT NULL,dispatch TEXT UNIQUE NOT NULL,
        binding TEXT NOT NULL,envelope TEXT NOT NULL,scope_digest TEXT NOT NULL,expires INTEGER NOT NULL,state TEXT NOT NULL,terminal_evidence TEXT,
        PRIMARY KEY(issuer,id));
      CREATE TABLE anchors(episode TEXT PRIMARY KEY,seq INTEGER NOT NULL,hash TEXT NOT NULL);
      CREATE TABLE audit(seq INTEGER PRIMARY KEY,body TEXT NOT NULL,hash TEXT NOT NULL,tag TEXT NOT NULL);`);
    }finally{db.close();}
    const a=fs.openSync(anchorLog,'wx',0o600);fs.fsyncSync(a);fs.closeSync(a);
  }
  verifyAudit(){
    let previous='',seq=0,time=0;
    for(const row of this.db.prepare('SELECT * FROM audit ORDER BY seq').all()){
      const body=JSON.parse(row.body);
      if(row.seq!==++seq||body.seq!==seq||body.previous!==previous||!Number.isSafeInteger(body.time)||body.time<time||canonical(body)!==row.body||digest(body)!==row.hash||
        !equalHex(row.tag,mac(this.key,{seq,hash:row.hash})))held('CUSTODIAN_AUDIT_INTEGRITY_HOLD');
      previous=row.hash;time=body.time;
    }
    const raw=fs.readFileSync(this.anchorLog,'utf8');
    const lines=raw?raw.split('\n'):[];if(raw&&!raw.endsWith('\n'))held('CUSTODIAN_ANCHOR_LOG_INCOMPLETE_HOLD');
    if(lines.length)lines.pop();let prior='',n=0;
    for(const text of lines){let a;try{a=JSON.parse(text);}catch{held('CUSTODIAN_ANCHOR_LOG_INCOMPLETE_HOLD');}
      if(a.seq!==++n||a.previous!==prior||!sha(a.hash)||!equalHex(a.tag,mac(this.key,{seq:a.seq,previous:a.previous,hash:a.hash})))held('CUSTODIAN_ANCHOR_LOG_INTEGRITY_HOLD');prior=a.hash;}
    if(seq!==n||previous!==prior)held('CUSTODIAN_DB_ANCHOR_DIVERGENCE_HOLD');
    if(this.now()<time)held('CUSTODIAN_CLOCK_REVERSED_HOLD');
    return {seq,hash:previous,time};
  }
  head(){
    const row=this.db.prepare('SELECT * FROM audit ORDER BY seq DESC LIMIT 1').get();
    const fd=fs.openSync(this.anchorLog,'r');let tail;
    try{const size=fs.fstatSync(fd).size;if(!size){if(row)held('CUSTODIAN_DB_ANCHOR_DIVERGENCE_HOLD');return {seq:0,hash:''};}
      const b=Buffer.alloc(Math.min(size,8192));fs.readSync(fd,b,0,b.length,size-b.length);tail=b.toString('utf8');
    }finally{fs.closeSync(fd);}
    if(!tail.endsWith('\n'))held('CUSTODIAN_ANCHOR_LOG_INCOMPLETE_HOLD');
    let a;try{a=JSON.parse(tail.split('\n').at(-2));}catch{held('CUSTODIAN_ANCHOR_LOG_INTEGRITY_HOLD');}
    if(!row||a.seq!==row.seq||a.hash!==row.hash||!equalHex(a.tag,mac(this.key,{seq:a.seq,previous:a.previous,hash:a.hash}))||
      !equalHex(row.tag,mac(this.key,{seq:row.seq,hash:row.hash}))||digest(JSON.parse(row.body))!==row.hash)held('CUSTODIAN_DB_ANCHOR_DIVERGENCE_HOLD');
    return {seq:row.seq,hash:row.hash,time:JSON.parse(row.body).time};
  }
  transaction(type,details,fn){
    if(this.fault)held(this.fault);
    this.db.exec('BEGIN IMMEDIATE');let result,receipt;
    try{
      const parent=this.head();result=fn();
      const clock=this.now();if(!Number.isSafeInteger(clock)||clock<(parent.time??0))held('CUSTODIAN_CLOCK_REVERSED_HOLD');
      const body={seq:parent.seq+1,previous:parent.hash,type,time:clock,details};
      if(Buffer.byteLength(canonical(body))>4096)held('CUSTODIAN_AUDIT_METADATA_BOUND_HOLD');
      const hash=digest(body),tag=mac(this.key,{seq:body.seq,hash});
      this.db.prepare('INSERT INTO audit VALUES(?,?,?,?)').run(body.seq,canonical(body),hash,tag);
      // The independent log is flushed while the DB write lock remains held.
      // A crash before COMMIT leaves a detectable divergence, never replay credit.
      const a={seq:body.seq,previous:parent.hash,hash};const line=canonical({...a,tag:mac(this.key,a)})+'\n';
      const fd=fs.openSync(this.anchorLog,'a');try{fs.writeSync(fd,line);fs.fsyncSync(fd);}finally{fs.closeSync(fd);}
      if(this.externalAudit)this.externalAudit.publish({issuer:this.issuer,seq:body.seq,hash,tag});
      this.db.exec('COMMIT');receipt={seq:body.seq,hash,tag,type,time:body.time};
    }catch(e){try{this.db.exec('ROLLBACK');}catch{}throw e;}
    return {value:result,receipt};
  }
  approveMandate(body){
    // No IPC route calls this method. Genuine authorization is the human-only
    // custody-account console gesture, not this JSON or possession of the key.
    if(!body?.id||!Number.isSafeInteger(body.expires)||body.expires<=this.now()||!Number.isSafeInteger(body.maxPermits)||body.maxPermits<1||
      !Array.isArray(body.allowedAttempts)||body.allowedAttempts.length!==body.maxPermits||new Set(body.allowedAttempts).size!==body.maxPermits||
      body.allowedAttempts.some(x=>typeof x!=='string'||!x)||!Number.isSafeInteger(body.permitLifetimeMs)||body.permitLifetimeMs<1||
      !sha(body.bindingPolicy?.executableSHA256)||!sha(body.bindingPolicy?.runtimePolicyDigest)||typeof body.bindingPolicy?.image!=='string'||
      !sha(body.operatorAuthorizationEvidenceDigest)||body.context?.audience!==this.audience)held('FINITE_HUMAN_MANDATE_REQUIRED');
    // Reuse the accepted bridge's complete context validation, without issuing.
    createSafeHarborDispatchBridge({context:body.context,trustedIssuers:this.roots(body),loadEnvelope:async()=>null,consumeAtomically:async()=>false,now:this.now});
    return this.transaction('HUMAN_MANDATE_RECORDED',{mandate:body.id,digest:digest(body)},()=>this.db.prepare('INSERT INTO mandates(id,body) VALUES(?,?)').run(body.id,canonical(body))).receipt;
  }
  roots(m){return {[this.issuer]:{key:this.key,application:'EXPERIMENT_B',namespacePrincipal:SAFE_HARBOR_NAMESPACE.principal,lane:EXPERIMENT_B_CUSTODY_LANE,
    operations:[scope],validFrom:0,validUntil:m.expires,maxPermitLifetimeMs:m.permitLifetimeMs}};}
  mandate(id){const row=this.db.prepare('SELECT * FROM mandates WHERE id=?').get(id);if(!row||row.revoked)held('MANDATE_MISSING_OR_REVOKED');
    const m=JSON.parse(row.body);if(this.now()>=m.expires)held('MANDATE_EXPIRED');return m;}
  issue(id,binding){
    const fields=['dispatchId','attempt','executableSHA256','promptSHA256','image','argumentsDigest','runtimePolicyDigest','captureId','inputMeasurementDigest'];
    if(!binding||Object.keys(binding).length!==fields.length||fields.some(k=>!Object.hasOwn(binding,k)))held('METADATA_ONLY_DISPATCH_BINDING_REQUIRED');
    return this.transaction('PERMIT_ISSUED',{mandate:id,attempt:binding?.attempt,dispatch:binding?.dispatchId},()=>{
      const m=this.mandate(id);
      if(!m.allowedAttempts.includes(binding?.attempt)||Object.entries(m.bindingPolicy).some(([k,v])=>canonical(binding[k]??null)!==canonical(v)))held('DISPATCH_OUTSIDE_HUMAN_MANDATE');
      if(this.db.prepare("SELECT count(*) AS n FROM permits WHERE state IN ('ISSUED','CONSUMED_UNCERTAIN')").get().n)held('UNRESOLVED_DISPATCH_HOLD');
      if(this.db.prepare('SELECT count(*) AS n FROM permits WHERE mandate=?').get(id).n>=m.maxPermits)held('FINITE_PERMIT_AUTHORITY_EXHAUSTED');
      const t=this.now(),payload={schema:'TD613_SAFE_HARBOR_FLIGHT_DISPATCH_V1',application:'EXPERIMENT_B',lane:EXPERIMENT_B_CUSTODY_LANE,operation:scope,
        namespace:SAFE_HARBOR_NAMESPACE,context:m.context,binding,issuer:this.issuer,authorizationId:randomUUID(),issuedAt:t,notBefore:t,expires:Math.min(m.expires,t+m.permitLifetimeMs)};
      const e=seal(this.key,payload);
      this.db.prepare('INSERT INTO permits VALUES(?,?,?,?,?,?,?,?,?,?,?)').run(this.issuer,payload.authorizationId,id,binding.attempt,binding.dispatchId,canonical(binding),canonical(e),digest(payload),payload.expires,'ISSUED',null);return e;
    }).value;
  }
  async consumeEnvelope(id,binding,envelope){
    const m=this.mandate(id);let receipt;
    const bridge=createSafeHarborDispatchBridge({context:m.context,trustedIssuers:this.roots(m),now:this.now,loadEnvelope:async()=>envelope,
      consumeAtomically:async claim=>{
        const accepted=this.transaction('DISPATCH_ACCEPTED_UNCERTAIN',{mandate:id,attempt:claim.attempt,dispatch:claim.dispatchId},()=>{
          this.mandate(id);const row=this.db.prepare('SELECT * FROM permits WHERE issuer=? AND id=?').get(claim.issuer,claim.authorizationId);
          if(!row||row.mandate!==id||row.state!=='ISSUED'||row.expires<=this.now()||row.scope_digest!==claim.scopeDigest||row.binding!==canonical(binding))held('PERMIT_REPLAY_EXPIRED_REVOKED_OR_SCOPE_HOLD');
          this.db.prepare("UPDATE permits SET state='CONSUMED_UNCERTAIN' WHERE issuer=? AND id=? AND state='ISSUED'").run(claim.issuer,claim.authorizationId);return true;
        });receipt=accepted.receipt;return accepted.value;
      }});
    await bridge.authorizeAndConsume(binding);return {status:'ACCEPTED',executionState:'CONSUMED_UNCERTAIN',receipt};
  }
  async authorizeAndConsume(id,binding){const envelope=this.issue(id,binding);return this.consumeEnvelope(id,binding,envelope);}
  revoke(id){return this.transaction('HUMAN_MANDATE_REVOKED',{mandate:id},()=>{
    this.db.prepare('UPDATE mandates SET revoked=1 WHERE id=?').run(id);
    this.db.prepare("UPDATE permits SET state='REVOKED' WHERE mandate=? AND state='ISSUED'").run(id);
  }).receipt;}
  lookup(attempt){const r=this.db.prepare('SELECT state,dispatch,scope_digest FROM permits WHERE attempt=?').get(attempt);return r?{state:r.state,dispatchId:r.dispatch,scopeDigest:r.scope_digest}:null;}
  recordTerminal(attempt,evidence){
    if(!sha(evidence?.journalHash)||!sha(evidence?.finalSHA256)||!sha(evidence?.jsonlSHA256))held('TERMINAL_EVIDENCE_COMMITMENTS_REQUIRED');
    return this.transaction('TERMINAL_COMMITMENTS_RECORDED',{attempt,evidence},()=>{
      const r=this.db.prepare('SELECT state,terminal_evidence FROM permits WHERE attempt=?').get(attempt);
      if(r?.state==='TERMINAL_RECORDED'&&r.terminal_evidence===canonical(evidence))return;
      if(r?.state!=='CONSUMED_UNCERTAIN')held('TERMINAL_SCOPE_HOLD');
      this.db.prepare("UPDATE permits SET state='TERMINAL_RECORDED',terminal_evidence=? WHERE attempt=?").run(canonical(evidence),attempt);
    }).receipt;
  }
  anchor(episode){return this.db.prepare('SELECT seq,hash FROM anchors WHERE episode=?').get(episode)??null;}
  publishAnchor(episode,event){
    if(!episode||!Number.isSafeInteger(event?.seq)||event.seq<1||!sha(event.hash)||!equalHex(event.signature,mac(this.checkpointKey,{seq:event.seq,hash:event.hash})))held('CHECKPOINT_AUTHENTICATION_HOLD');
    const prior=this.anchor(episode);
    if(prior?.seq===event.seq&&prior?.hash===event.hash)return prior;
    return this.transaction('CHECKPOINT_MINIMUM_ADVANCED',{episode,seq:event.seq,hash:event.hash},()=>{
      const old=this.anchor(episode);
      if(old&&(event.seq!==old.seq+1||event.previous!==old.hash)||!old&&(event.seq!==1||event.previous!==''))held('CHECKPOINT_ROLLBACK_OR_GAP_HOLD');
      this.db.prepare('INSERT INTO anchors VALUES(?,?,?) ON CONFLICT(episode) DO UPDATE SET seq=excluded.seq,hash=excluded.hash').run(episode,event.seq,event.hash);
      return {seq:event.seq,hash:event.hash};
    }).value;
  }
  refusal(code,requestDigest){return this.transaction('REFUSAL_OR_HOLD',{code,requestDigest},()=>null).receipt;}
  close(){this.db.close();this.key.fill(0);this.checkpointKey.fill(0);}
}
