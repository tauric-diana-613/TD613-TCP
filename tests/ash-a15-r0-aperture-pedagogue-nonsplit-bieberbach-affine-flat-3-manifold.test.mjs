assert.equal(all.passed,true);
assert.equal(all.hard_ceilings.physical_spacetime,false);
assert.equal(all.hard_ceilings.td613_curvature,false);
assert.equal(all.hard_ceilings.geometric_two_holonomy,false);
assert.equal(all.hard_ceilings.berry_gerbe_holonomy,false);
assert.equal(all.hard_ceilings.operational_route_group,false);
assert.equal(all.hard_ceilings.ontology,false);
assert.equal(all.candidate_classifications.includes('NONSPLIT_BIEBERBACH_AFFINE_FLAT_THREE_MANIFOLD_INSTANTIATION_EARNED'),true);

